-- Projeto TABD | PostgreSQL 17
-- Inicializado automaticamente SOMENTE quando o volume Docker esta vazio.
-- ORIGEM: DDL dos anexos 8.3 e 8.4 da primeira entrega; sintaxe Oracle adaptada.
-- O DW e as tabelas staging NAO sao populados durante a inicializacao.

BEGIN;

CREATE SCHEMA oltp;
CREATE SCHEMA staging;
CREATE SCHEMA dw;

-- ======================== FONTE OLTP - ONE PIECE ========================
CREATE TABLE oltp.saga (
    id_saga INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_saga VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT ck_saga_nome CHECK (length(btrim(nome_saga)) > 0)
);

CREATE TABLE oltp.arco (
    id_arco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_saga INTEGER NOT NULL REFERENCES oltp.saga(id_saga),
    nome_arco VARCHAR(100) NOT NULL UNIQUE,
    qtd_capitulos SMALLINT NOT NULL CHECK (qtd_capitulos > 0),
    ano_inicio SMALLINT NOT NULL CHECK (ano_inicio BETWEEN 1997 AND 2024),
    ano_fim SMALLINT NOT NULL CHECK (ano_fim BETWEEN 1997 AND 2024),
    op_final NUMERIC(2,1) NOT NULL CHECK (op_final BETWEEN 0 AND 3),
    des_final NUMERIC(2,1) NOT NULL CHECK (des_final BETWEEN 0 AND 3),
    dis_final NUMERIC(2,1) NOT NULL CHECK (dis_final BETWEEN 0 AND 3),
    res_final NUMERIC(2,1) NOT NULL CHECK (res_final BETWEEN 0 AND 3),
    isa_final NUMERIC(3,1) NOT NULL CHECK (isa_final BETWEEN 0 AND 12),
    CONSTRAINT ck_arco_periodo CHECK (ano_fim >= ano_inicio),
    CONSTRAINT ck_arco_isa CHECK (isa_final = op_final + des_final + dis_final + res_final),
    CONSTRAINT ck_arco_nome CHECK (length(btrim(nome_arco)) > 0)
);

CREATE OR REPLACE VIEW oltp.vw_arcos_analise AS
SELECT
    a.id_arco, a.nome_arco, a.id_saga, s.nome_saga,
    a.qtd_capitulos, a.ano_inicio, a.ano_fim,
    (a.ano_fim - a.ano_inicio + 1) AS duracao_publicacao_anos,
    a.op_final, a.des_final, a.dis_final, a.res_final, a.isa_final
FROM oltp.arco a
JOIN oltp.saga s ON s.id_saga = a.id_saga;

-- ======================== STAGING - V-DEM ========================
-- Grao: um ano; nova tabela operacional proposta para o pipeline Pentaho.
CREATE TABLE staging.stg_vdem_anual (
    year SMALLINT PRIMARY KEY CHECK (year BETWEEN 1997 AND 2024),
    v2x_clpol NUMERIC(7,5) CHECK (v2x_clpol BETWEEN 0 AND 1),
    v2xeg_eqdr NUMERIC(7,5) CHECK (v2xeg_eqdr BETWEEN 0 AND 1),
    v2xeg_eqprotec NUMERIC(7,5) CHECK (v2xeg_eqprotec BETWEEN 0 AND 1),
    v2x_cspart NUMERIC(7,5) CHECK (v2x_cspart BETWEEN 0 AND 1),
    op_real NUMERIC(7,5) CHECK (op_real BETWEEN 0 AND 1),
    des_real NUMERIC(7,5) CHECK (des_real BETWEEN 0 AND 1),
    dis_real NUMERIC(7,5) CHECK (dis_real BETWEEN 0 AND 1),
    part_civil_real NUMERIC(7,5) CHECK (part_civil_real BETWEEN 0 AND 1),
    qtd_paises_v2x_clpol INTEGER CHECK (qtd_paises_v2x_clpol >= 0),
    qtd_paises_v2xeg_eqdr INTEGER CHECK (qtd_paises_v2xeg_eqdr >= 0),
    qtd_paises_v2xeg_eqprotec INTEGER CHECK (qtd_paises_v2xeg_eqprotec >= 0),
    qtd_paises_v2x_cspart INTEGER CHECK (qtd_paises_v2x_cspart >= 0)
);

-- Grao: um arco; tabela ja prevista no documento de modelagem.
CREATE TABLE staging.stg_vdem_arco (
    id_arco_origem INTEGER PRIMARY KEY REFERENCES oltp.arco(id_arco),
    op_real NUMERIC(7,6) CHECK (op_real BETWEEN 0 AND 1),
    des_real NUMERIC(7,6) CHECK (des_real BETWEEN 0 AND 1),
    dis_real NUMERIC(7,6) CHECK (dis_real BETWEEN 0 AND 1),
    part_civil_real NUMERIC(7,6) CHECK (part_civil_real BETWEEN 0 AND 1)
);

-- ======================== DATA WAREHOUSE ========================
CREATE TABLE dw.dim_tempo (
    sk_tempo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano SMALLINT NOT NULL UNIQUE CHECK (ano BETWEEN 1997 AND 2024),
    decada SMALLINT NOT NULL,
    CONSTRAINT ck_dim_tempo_decada CHECK (decada = (ano / 10) * 10)
);

CREATE TABLE dw.dim_saga (
    sk_saga INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_saga_origem INTEGER NOT NULL UNIQUE,
    nome_saga VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE dw.dim_arco (
    sk_arco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_arco_origem INTEGER NOT NULL UNIQUE,
    nome_arco VARCHAR(100) NOT NULL UNIQUE
);

-- Grao da fato: exatamente um registro para cada arco.
CREATE TABLE dw.fato_sociopolitica_arco (
    sk_fato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sk_arco INTEGER NOT NULL UNIQUE REFERENCES dw.dim_arco(sk_arco),
    sk_saga INTEGER NOT NULL REFERENCES dw.dim_saga(sk_saga),
    sk_tempo_inicio INTEGER NOT NULL REFERENCES dw.dim_tempo(sk_tempo),
    sk_tempo_fim INTEGER NOT NULL REFERENCES dw.dim_tempo(sk_tempo),
    qtd_capitulos SMALLINT NOT NULL CHECK (qtd_capitulos > 0),
    duracao_publicacao_anos SMALLINT NOT NULL CHECK (duracao_publicacao_anos > 0),
    op_final NUMERIC(2,1) NOT NULL CHECK (op_final BETWEEN 0 AND 3),
    des_final NUMERIC(2,1) NOT NULL CHECK (des_final BETWEEN 0 AND 3),
    dis_final NUMERIC(2,1) NOT NULL CHECK (dis_final BETWEEN 0 AND 3),
    res_final NUMERIC(2,1) NOT NULL CHECK (res_final BETWEEN 0 AND 3),
    isa_final NUMERIC(3,1) NOT NULL CHECK (isa_final BETWEEN 0 AND 12),
    op_real NUMERIC(7,6) CHECK (op_real BETWEEN 0 AND 1),
    des_real NUMERIC(7,6) CHECK (des_real BETWEEN 0 AND 1),
    dis_real NUMERIC(7,6) CHECK (dis_real BETWEEN 0 AND 1),
    part_civil_real NUMERIC(7,6) CHECK (part_civil_real BETWEEN 0 AND 1),
    qtd_arcos SMALLINT NOT NULL DEFAULT 1 CHECK (qtd_arcos = 1),
    CONSTRAINT ck_fato_isa CHECK (isa_final = op_final + des_final + dis_final + res_final)
);

-- Indices para acelerar filtros/joins pelas FKs nao exclusivas.
CREATE INDEX idx_fato_saga ON dw.fato_sociopolitica_arco(sk_saga);
CREATE INDEX idx_fato_tempo_inicio ON dw.fato_sociopolitica_arco(sk_tempo_inicio);
CREATE INDEX idx_fato_tempo_fim ON dw.fato_sociopolitica_arco(sk_tempo_fim);

COMMIT;
